// Wallet setup for the Omega swarm: one deployer/facilitator, three P-256 steward keys, and one
// HD-derived EVM wallet per agent. Secrets go to .env (git-ignored, chmod 600) and are never printed.
// Public addresses go to agents/wallets.public.json, which is safe to commit.
//
//   node agents/wallets.mjs init     create .env if it does not exist (refuses to overwrite)
//   node agents/wallets.mjs derive   (re)write agents/wallets.public.json from .env + agents/roster.json
import { Wallet, HDNodeWallet, Mnemonic } from 'ethers';
import { generateKeyPairSync } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, chmodSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ENV = join(ROOT, '.env');

export function loadEnv() {
  if (!existsSync(ENV)) throw new Error('.env missing: run `node agents/wallets.mjs init` first');
  const env = {};
  for (const line of readFileSync(ENV, 'utf8').split('\n')) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) env[m[1]] = m[2].replace(/^"|"$/g, '');
  }
  return env;
}

/** Agent i's wallet: BIP-44 path m/44'/60'/0'/0/i from the swarm mnemonic. */
export function agentWallet(env, index) {
  return HDNodeWallet.fromMnemonic(Mnemonic.fromPhrase(env.AGENT_MNEMONIC), `m/44'/60'/0'/0/${index}`);
}

function p256() {
  const { privateKey, publicKey } = generateKeyPairSync('ec', { namedCurve: 'P-256' });
  const jwk = publicKey.export({ format: 'jwk' });
  return {
    pkcs8: Buffer.from(privateKey.export({ format: 'pem', type: 'pkcs8' })).toString('base64'),
    x: '0x' + Buffer.from(jwk.x, 'base64url').toString('hex'),
    y: '0x' + Buffer.from(jwk.y, 'base64url').toString('hex'),
  };
}

function init() {
  if (existsSync(ENV)) { console.log('.env already exists; not overwriting.'); return; }
  const deployer = Wallet.createRandom();
  const swarm = Wallet.createRandom().mnemonic.phrase;
  const stewards = [1, 2, 3].map(() => p256());
  const lines = [
    '# Generated by agents/wallets.mjs. NEVER commit or share this file.',
    `DEPLOYER_PRIVATE_KEY=${deployer.privateKey}`,
    `DEPLOYER_ADDRESS=${deployer.address}`,
    `AGENT_MNEMONIC="${swarm}"`,
    ...stewards.flatMap((s, i) => [
      `STEWARD${i + 1}_P256_PKCS8=${s.pkcs8}`,
      `STEWARD${i + 1}_P256_X=${s.x}`,
      `STEWARD${i + 1}_P256_Y=${s.y}`,
    ]),
    // Dwellir Monad testnet (full node). The key goes in DWELLIR_API_KEY and is sent as the X-Api-Key header.
    'MONAD_TESTNET_RPC=https://api-monad-testnet-full.n.dwellir.com',
    'DWELLIR_API_KEY=',
    'CHAIN_ID=10143',
  ];
  writeFileSync(ENV, lines.join('\n') + '\n', { mode: 0o600 });
  chmodSync(ENV, 0o600);
  console.log('Created .env (mode 600).');
  console.log('Deployer / facilitator address (fund this from the Monad testnet faucet):', deployer.address);
}

function derive() {
  const env = loadEnv();
  const roster = JSON.parse(readFileSync(join(ROOT, 'agents/roster.json'), 'utf8'));
  const out = {
    note: 'Public addresses only. Private keys stay in the local .env; agent keys are HD-derived (m/44\'/60\'/0\'/0/i).',
    chainId: Number(env.CHAIN_ID),
    deployer: env.DEPLOYER_ADDRESS,
    stewards: [1, 2, 3].map((k) => ({ id: k, p256: { x: env[`STEWARD${k}_P256_X`], y: env[`STEWARD${k}_P256_Y`] } })),
    agents: roster.agents.map((a, i) => ({ index: i, slug: a.slug, address: agentWallet(env, i).address })),
  };
  writeFileSync(join(ROOT, 'agents/wallets.public.json'), JSON.stringify(out, null, 2) + '\n');
  console.log(`Wrote agents/wallets.public.json: ${out.agents.length} agent wallets, 3 stewards.`);
}

// CLI only when run directly (this module is also imported by the deploy and agent scripts).
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const cmd = process.argv[2];
  if (cmd === 'init') init();
  else if (cmd === 'derive') derive();
  else { console.error('usage: node agents/wallets.mjs init|derive'); process.exit(1); }
}
