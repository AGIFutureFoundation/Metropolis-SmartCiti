"""Build agents/roster.json from the AGI Corp worlds registries (private repo, copied to /tmp/acw by
`gh api`) plus the founder's three Virtuals agents. Every entry cites its source file, so nothing here
is invented. Roles: 0 coordinator, 1 tutor, 2 robot, 3 sensor/QA, 4 steward-liaison (Omega).

    python3 agents/build_roster.py /tmp/acw
"""
import json
import sys
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else '/tmp/acw')
OUT = Path(__file__).with_name('roster.json')

agents = []


def add(slug, name, role, desc, source, **extra):
    agents.append({'slug': slug, 'name': name, 'role': role, 'description': desc, 'source': source, **extra})


# 1) Swarm coordinators + specialists that run the robotics network and its payments
for f in ['robotics-dao.json', 'agentic-payments.json']:
    s = json.loads((SRC / f).read_text())
    c = s['coordinator']
    add(c['id'], c['name'], 0, f"Coordinator of the {s['world']} swarm ({s['topology']})", f'agi-corp-worlds/agents/swarms/{f}')
    for a in s['agents']:
        add(a['id'], a['name'], 1 if 'robotics' in a['id'] else 0, a['role'], f'agi-corp-worlds/agents/swarms/{f}')

# 2) One robot agent per SmartCiti.X Holodeck simulator module (they earn tOMEGA per graded run)
r = json.loads((SRC / 'index.json').read_text())
for m in r['modules']:
    if m['id'].startswith('smartciti-holodeck.'):
        add(m['id'].replace('smartciti-holodeck.', 'robot.'), f"{m['title']} Robot", 2,
            f"Simulated robot for the '{m['title']}' module; replays signed simulator runs (no physical dispatch)",
            'agi-corp-worlds/agents/robotics/index.json')

# 3) The founder's Virtuals agents (identity lives on Base via Virtuals ACP; linked, not custodied)
add('virtuals.tactile-sense', 'Tactile ($SENSE)', 3,
    'Robotic sensing agent: enhanced sensing, feedback and environmental awareness. Grades robot runs (QA).',
    'api.virtuals.io/api/virtuals/86726',
    virtuals={'id': 86726, 'chain': 'BASE', 'wallet': '0x8Bda2a3Fc36E98E601a4EB43457A23835725B102',
              'preToken': '0xA79940260B7911DCA22E3730114e5BcA845ef397', 'url': 'https://app.virtuals.io/virtuals/86726'})
for acp in ['01a1225a-1f57-7bd0-b0b5-c9f0737461b2', '019ebb52-4797-7b3f-b3fc-b970e862a3f6']:
    add(f'virtuals.acp-{acp[:8]}', f'Virtuals ACP agent {acp[:8]}', 0,
        'Founder ACP agent; offerings and wallet resolved after `acp configure` (login required).',
        f'https://app.virtuals.io/acp/agents/{acp}', virtuals={'acpAgentId': acp, 'url': f'https://app.virtuals.io/acp/agents/{acp}'})

# 4) The 44 Omega stewards: agent seats that brief humans; they can pay for research but never vote
o = json.loads((SRC / 'omega_agents.json').read_text())
for om in o['omegas']:
    add(om['id'], om['title'], 4, f"Steward liaison for {om['corporation']['name']} (seat for people; agent briefs and pays for research only)",
        'agi-corp-worlds/agents/advisory/omega_agents.json')

roster = {
    'note': 'Generated by agents/build_roster.py from the AGI Corp worlds registries. Roles: 0 coordinator, 1 tutor, 2 robot, 3 sensor/QA, 4 steward-liaison.',
    'omega_token': {
        'onchain_here': 'tOMEGA (Monad testnet stand-in, no market value)',
        'canonical': 'founder $OMEGA (Virtuals). Mint address to be confirmed by the founder; see README.',
    },
    'may_never': o['may_never'],
    'agents': agents,
}
OUT.write_text(json.dumps(roster, indent=2) + '\n')
by_role = {}
for a in agents:
    by_role[a['role']] = by_role.get(a['role'], 0) + 1
print(f'{len(agents)} agents -> {OUT.name}; by role {by_role}')
